    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // Update the text Message
        String sms_template_id = String.valueOf(jTable1.getValueAt(jTable1.getSelectedRow(), 0));
        if (!jTextArea2.getText().isEmpty()) {
            MySQL.execute("UPDATE `sms_templates` SET `message` = '" + jTextArea2.getText() + "' WHERE `id` = '" + sms_template_id + "'");
            refresh();
        } else {
            JOptionPane.showMessageDialog(this, "Empty Sms Text. invalid input", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton4ActionPerformed

