    public void calculateSMStext() {
        String txtMessage = jTextArea2.getText();
        if (!txtMessage.isEmpty()) {
            SMSInfo info = SMSCalculator.calculate(txtMessage);
            lblUnits.setText(String.valueOf(info.getUnits()));
            lblCharacters.setText(String.valueOf(info.getCharacters()));
            lblRemaining.setText(info.getRemaining());
            lblCharactersPerUnit.setText(String.valueOf(info.getCharactersPerUnit()));
            lblEncoding.setText(info.getEncoding());
        } else {
            lblUnits.setText("1");
            lblCharacters.setText("0");
            lblRemaining.setText("160");
            lblEncoding.setText("_");
        }
    }

    public void loadTemplates() {
        try {
//            aniwaren Login wenna wenawa
            ResultSet rs = MySQL.execute("SELECT * FROM `sms_templates` ");
            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {

                Vector v = new Vector();
                v.add(rs.getString("id"));
                v.add(rs.getString("message_name"));
                v.add(rs.getString("message"));

                dtm.addRow(v);
            }

        } catch (SQLException se) {
            se.printStackTrace();
            JOptionPane.showMessageDialog(this, "Please Check Your Internet Conneciton", "Connection Error", JOptionPane.ERROR_MESSAGE);
            logger.log(Level.WARNING, "Data failed to load", se);

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Something Wrong Please Try again Later", "Error", JOptionPane.ERROR_MESSAGE);
            logger.log(Level.WARNING, "Data failed to load", e);

        }
    }

